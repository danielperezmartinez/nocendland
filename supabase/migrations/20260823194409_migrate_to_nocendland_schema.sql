create or replace view nocendland.nutrition_intake_with_totals
with (security_invoker = true)
as
select
  intake.id as intake_id,
  intake.ingredient,
  intake.quantity_in_grams,
  ingredient.name as ingredient_name,
  (
    ingredient.calories_per_100::numeric
      * intake.quantity_in_grams::numeric
      / 100::numeric
  )::bigint as calories,
  ingredient.proteins_per_100 * intake.quantity_in_grams::double precision
    / 100::double precision as proteins,
  ingredient.fats_per_100 * intake.quantity_in_grams::double precision
    / 100::double precision as fats,
  ingredient.carbohydrates_per_100 * intake.quantity_in_grams::double precision
    / 100::double precision as carbohydrates,
  intake.date,
  intake.id_user
from nocendland.nutrition_intake intake
join nocendland.nutrition_ingredient ingredient on intake.ingredient = ingredient.id;

create or replace view nocendland.nutrition_objectives_totals
with (security_invoker = true)
as
select
  sum(intake.calories) as calories,
  sum(intake.proteins) as proteins,
  sum(intake.fats) as fats,
  sum(intake.carbohydrates) as carbohydrates,
  intake.date,
  intake.id_user
from nocendland.nutrition_intake_with_totals intake
group by intake.date, intake.id_user;

