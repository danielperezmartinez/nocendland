create or replace function nocendland.ensure_training_schedule()
returns nocendland.training_schedule
language plpgsql
security invoker
set search_path = ''
as $$
declare
  result nocendland.training_schedule;
  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then
    raise exception 'authentication_required';
  end if;

  select * into result
  from nocendland.training_schedule
  where id_user = current_user_id
  order by is_active desc, created_at, id
  limit 1;

  if result.id is null then
    insert into nocendland.training_schedule (id_user, name, is_active)
    values (current_user_id, 'Horario 1', true)
    returning * into result;
  end if;

  return result;
exception
  when unique_violation then
    select * into result
    from nocendland.training_schedule
    where id_user = current_user_id
    order by is_active desc, created_at, id
    limit 1;
    return result;
end;
$$;

create or replace function nocendland.activate_training_schedule(target_schedule_id bigint)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then
    raise exception 'authentication_required';
  end if;

  if not exists (
    select 1 from nocendland.training_schedule
    where id = target_schedule_id and id_user = current_user_id
  ) then
    raise exception 'schedule_not_found';
  end if;

  update nocendland.training_schedule
  set is_active = false, updated_at = now()
  where id_user = current_user_id and is_active;

  update nocendland.training_schedule
  set is_active = true, updated_at = now()
  where id = target_schedule_id and id_user = current_user_id;
end;
$$;

create or replace function nocendland_private.enforce_training_active_schedule()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  affected_user_id uuid := coalesce(new.id_user, old.id_user);
begin
  -- Durante el borrado en cascada de un usuario ya no hay un catálogo que proteger.
  if not exists (select 1 from nocendland."user" where id = affected_user_id) then
    return null;
  end if;

  if exists (select 1 from nocendland.training_schedule where id_user = affected_user_id)
    and not exists (
      select 1
      from nocendland.training_schedule
      where id_user = affected_user_id and is_active
    ) then
    raise exception 'active_schedule_required';
  end if;

  return null;
end;
$$;

create constraint trigger training_schedule_requires_active
after insert or update or delete on nocendland.training_schedule
deferrable initially deferred
for each row execute function nocendland_private.enforce_training_active_schedule();

create or replace function nocendland.import_training_share_manifest(
  shared_manifest jsonb,
  conflict_actions jsonb default '{}'::jsonb,
  activate_schedule boolean default false,
  source_share uuid default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  shared_exercise jsonb;
  shared_day jsonb;
  shared_item jsonb;
  shared_portable_id uuid;
  local_exercise_id bigint;
  local_schedule_id bigint;
  local_schedule_name text;
  base_schedule_name text;
  name_suffix integer := 1;
  exercise_mapping jsonb := '{}'::jsonb;
  action text;
begin
  if current_user_id is null then
    raise exception 'authentication_required';
  end if;

  if shared_manifest ->> 'version' <> 'training-share/v1'
    or shared_manifest ->> 'type' not in ('exercises', 'schedule')
    or jsonb_typeof(shared_manifest -> 'exercises') <> 'array' then
    raise exception 'invalid_training_share_manifest';
  end if;

  perform nocendland.ensure_training_schedule();

  for shared_exercise in
    select value from jsonb_array_elements(shared_manifest -> 'exercises')
  loop
    shared_portable_id := (shared_exercise ->> 'portableId')::uuid;
    action := coalesce(conflict_actions ->> shared_portable_id::text, 'keep');

    if action not in ('keep', 'update') then
      raise exception 'invalid_conflict_action';
    end if;

    select id into local_exercise_id
    from nocendland.training_exercise
    where id_user = current_user_id and portable_id = shared_portable_id;

    if local_exercise_id is null then
      insert into nocendland.training_exercise (
        id_user,
        portable_id,
        name,
        description,
        tips,
        image_path,
        video_url,
        training_modalities,
        muscle_groups,
        movement_patterns
      ) values (
        current_user_id,
        shared_portable_id,
        btrim(shared_exercise ->> 'name'),
        nullif(btrim(coalesce(shared_exercise ->> 'description', '')), ''),
        coalesce(array(select jsonb_array_elements_text(shared_exercise -> 'tips')), '{}'::text[]),
        null,
        nullif(btrim(coalesce(shared_exercise ->> 'videoUrl', '')), ''),
        coalesce(array(select jsonb_array_elements_text(coalesce(shared_exercise -> 'trainingModalities', '[]'::jsonb))), '{}'::text[]),
        coalesce(array(select jsonb_array_elements_text(coalesce(shared_exercise -> 'muscleGroups', '[]'::jsonb))), '{}'::text[]),
        coalesce(array(select jsonb_array_elements_text(coalesce(shared_exercise -> 'movementPatterns', '[]'::jsonb))), '{}'::text[])
      ) returning id into local_exercise_id;
    elsif action = 'update' then
      update nocendland.training_exercise
      set name = btrim(shared_exercise ->> 'name'),
          description = nullif(btrim(coalesce(shared_exercise ->> 'description', '')), ''),
          tips = coalesce(array(select jsonb_array_elements_text(shared_exercise -> 'tips')), '{}'::text[]),
          video_url = nullif(btrim(coalesce(shared_exercise ->> 'videoUrl', '')), ''),
          training_modalities = coalesce(array(select jsonb_array_elements_text(coalesce(shared_exercise -> 'trainingModalities', '[]'::jsonb))), '{}'::text[]),
          muscle_groups = coalesce(array(select jsonb_array_elements_text(coalesce(shared_exercise -> 'muscleGroups', '[]'::jsonb))), '{}'::text[]),
          movement_patterns = coalesce(array(select jsonb_array_elements_text(coalesce(shared_exercise -> 'movementPatterns', '[]'::jsonb))), '{}'::text[]),
          archived_at = null,
          updated_at = now()
      where id = local_exercise_id and id_user = current_user_id;
    end if;

    exercise_mapping := exercise_mapping
      || jsonb_build_object(shared_portable_id::text, local_exercise_id);
  end loop;

  if shared_manifest ->> 'type' = 'schedule' then
    if jsonb_typeof(shared_manifest -> 'schedule') <> 'object'
      or jsonb_typeof(shared_manifest -> 'schedule' -> 'days') <> 'array' then
      raise exception 'invalid_training_schedule_manifest';
    end if;

    shared_portable_id := (shared_manifest -> 'schedule' ->> 'portableId')::uuid;
    if exists (
      select 1 from nocendland.training_schedule
      where id_user = current_user_id and portable_id = shared_portable_id
    ) then
      raise exception 'schedule_already_imported';
    end if;

    base_schedule_name := btrim(shared_manifest -> 'schedule' ->> 'name');
    local_schedule_name := base_schedule_name;
    while exists (
      select 1 from nocendland.training_schedule
      where id_user = current_user_id and lower(btrim(name)) = lower(local_schedule_name)
    ) loop
      name_suffix := name_suffix + 1;
      local_schedule_name := base_schedule_name || ' (' || name_suffix || ')';
    end loop;

    if activate_schedule then
      update nocendland.training_schedule
      set is_active = false, updated_at = now()
      where id_user = current_user_id and is_active;
    end if;

    insert into nocendland.training_schedule (
      id_user, portable_id, name, is_active, source_share_id
    ) values (
      current_user_id, shared_portable_id, local_schedule_name, activate_schedule, source_share
    ) returning id into local_schedule_id;

    for shared_day in
      select value from jsonb_array_elements(shared_manifest -> 'schedule' -> 'days')
    loop
      if (shared_day ->> 'weekday')::integer not between 1 and 7
        or jsonb_typeof(shared_day -> 'items') <> 'array' then
        raise exception 'invalid_training_schedule_day';
      end if;

      for shared_item in
        select value from jsonb_array_elements(shared_day -> 'items')
      loop
        local_exercise_id :=
          (exercise_mapping ->> (shared_item ->> 'exercisePortableId'))::bigint;
        if local_exercise_id is null then
          raise exception 'missing_training_schedule_exercise';
        end if;

        insert into nocendland.training_schedule_item (
          id_user, schedule_id, exercise_id, weekday, set_count,
          target_repetitions, target_weight_kg, sort_order
        ) values (
          current_user_id,
          local_schedule_id,
          local_exercise_id,
          (shared_day ->> 'weekday')::smallint,
          (shared_item ->> 'setCount')::smallint,
          nullif(shared_item ->> 'targetRepetitions', '')::smallint,
          nullif(shared_item ->> 'targetWeightKg', '')::numeric,
          (shared_item ->> 'sortOrder')::integer
        );
      end loop;
    end loop;
  end if;

  return jsonb_build_object(
    'exerciseIds', exercise_mapping,
    'scheduleId', local_schedule_id,
    'scheduleName', local_schedule_name
  );
end;
$$;

create or replace function nocendland.save_training_schedule_catalog(
  catalog_draft jsonb,
  selected_key text
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  draft_item jsonb;
  created_schedule_id bigint;
  active_schedule_id bigint;
  selected_schedule_id bigint;
  schedule_ids jsonb := '{}'::jsonb;
begin
  if current_user_id is null then
    raise exception 'authentication_required';
  end if;

  if jsonb_typeof(catalog_draft) <> 'array'
    or jsonb_array_length(catalog_draft) = 0 then
    raise exception 'invalid_training_schedule_catalog';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(catalog_draft) item
    where nullif(btrim(item ->> 'key'), '') is null
      or (not coalesce((item ->> 'deleted')::boolean, false)
        and nullif(btrim(item ->> 'name'), '') is null)
      or ((item ->> 'id') is null and coalesce((item ->> 'deleted')::boolean, false))
      or ((item ->> 'id') is not null and (item ->> 'duplicateFromId') is not null)
  ) then
    raise exception 'invalid_training_schedule_catalog';
  end if;

  if (
    select count(*)
    from jsonb_array_elements(catalog_draft) item
    where not coalesce((item ->> 'deleted')::boolean, false)
  ) = 0 then
    raise exception 'training_schedule_required';
  end if;

  if (
    select count(*)
    from jsonb_array_elements(catalog_draft) item
    where not coalesce((item ->> 'deleted')::boolean, false)
      and coalesce((item ->> 'isActive')::boolean, false)
  ) <> 1 then
    raise exception 'single_active_training_schedule_required';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(catalog_draft) item
    group by item ->> 'key'
    having count(*) > 1
  ) or exists (
    select 1
    from jsonb_array_elements(catalog_draft) item
    where not coalesce((item ->> 'deleted')::boolean, false)
    group by lower(btrim(item ->> 'name'))
    having count(*) > 1
  ) then
    raise exception 'duplicate_training_schedule_catalog_value';
  end if;

  if not exists (
    select 1
    from jsonb_array_elements(catalog_draft) item
    where item ->> 'key' = selected_key
      and not coalesce((item ->> 'deleted')::boolean, false)
  ) then
    raise exception 'invalid_selected_training_schedule';
  end if;

  -- El conjunto completo y updated_at funcionan como control de concurrencia optimista.
  if exists (
    select 1
    from nocendland.training_schedule schedule
    where schedule.id_user = current_user_id
      and not exists (
        select 1 from jsonb_array_elements(catalog_draft) item
        where (item ->> 'id')::bigint = schedule.id
      )
  ) or exists (
    select 1
    from jsonb_array_elements(catalog_draft) item
    left join nocendland.training_schedule schedule
      on schedule.id = (item ->> 'id')::bigint
      and schedule.id_user = current_user_id
    where (item ->> 'id') is not null
      and (schedule.id is null
        or (item ->> 'updatedAt') is null
        or schedule.updated_at <> (item ->> 'updatedAt')::timestamptz)
  ) then
    raise exception 'stale_training_schedule_catalog';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(catalog_draft) item
    left join nocendland.training_schedule schedule
      on schedule.id = (item ->> 'duplicateFromId')::bigint
      and schedule.id_user = current_user_id
    where (item ->> 'duplicateFromId') is not null and schedule.id is null
  ) then
    raise exception 'invalid_training_schedule_duplicate';
  end if;

  -- Los nombres temporales permiten intercambiar nombres sin violar el índice único.
  update nocendland.training_schedule
  set name = '__catalog_' || gen_random_uuid()::text,
      is_active = false,
      updated_at = now()
  where id_user = current_user_id;

  for draft_item in select value from jsonb_array_elements(catalog_draft)
  loop
    if not coalesce((draft_item ->> 'deleted')::boolean, false)
      and (draft_item ->> 'id') is not null then
      update nocendland.training_schedule
      set name = btrim(draft_item ->> 'name'), updated_at = now()
      where id = (draft_item ->> 'id')::bigint and id_user = current_user_id;

      schedule_ids := schedule_ids || jsonb_build_object(
        draft_item ->> 'key',
        (draft_item ->> 'id')::bigint
      );
    end if;
  end loop;

  for draft_item in select value from jsonb_array_elements(catalog_draft)
  loop
    if (draft_item ->> 'id') is null then
      insert into nocendland.training_schedule (id_user, name, is_active)
      values (current_user_id, btrim(draft_item ->> 'name'), false)
      returning id into created_schedule_id;

      if (draft_item ->> 'duplicateFromId') is not null then
        insert into nocendland.training_schedule_item (
          id_user, schedule_id, exercise_id, weekday, set_count,
          target_repetitions, target_weight_kg, sort_order
        )
        select
          current_user_id, created_schedule_id, exercise_id, weekday, set_count,
          target_repetitions, target_weight_kg, sort_order
        from nocendland.training_schedule_item
        where id_user = current_user_id
          and schedule_id = (draft_item ->> 'duplicateFromId')::bigint;
      end if;

      schedule_ids := schedule_ids
        || jsonb_build_object(draft_item ->> 'key', created_schedule_id);
    end if;
  end loop;

  select (schedule_ids ->> (item ->> 'key'))::bigint into active_schedule_id
  from jsonb_array_elements(catalog_draft) item
  where not coalesce((item ->> 'deleted')::boolean, false)
    and coalesce((item ->> 'isActive')::boolean, false);

  update nocendland.training_schedule
  set is_active = true, updated_at = now()
  where id = active_schedule_id and id_user = current_user_id;

  delete from nocendland.training_schedule schedule
  using jsonb_array_elements(catalog_draft) item
  where coalesce((item ->> 'deleted')::boolean, false)
    and schedule.id = (item ->> 'id')::bigint
    and schedule.id_user = current_user_id;

  selected_schedule_id := (schedule_ids ->> selected_key)::bigint;
  return jsonb_build_object(
    'scheduleIds', schedule_ids,
    'selectedScheduleId', selected_schedule_id
  );
end;
$$;

