    references nocendland."user"(id) on update cascade on delete cascade,
  name text not null,
  target_amount numeric(14, 2) not null,
  initial_amount numeric(14, 2) not null default 0,
  target_date date,
  status text not null default 'active',
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint finance_goal_id_owner_key unique (id, id_user),
  constraint finance_goal_name_check check (btrim(name) <> ''),
  constraint finance_goal_target_amount_check check (target_amount > 0),
  constraint finance_goal_initial_amount_check check (initial_amount >= 0),
  constraint finance_goal_status_check
    check (status in ('active', 'completed', 'archived'))
);

