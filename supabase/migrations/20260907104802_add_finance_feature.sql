create or replace function nocendland.ensure_finance_period(target_date date default current_date)
returns nocendland.finance_period
language plpgsql
security invoker
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  configured_start_day smallint;
  target_month date;
  previous_month date;
  next_month date;
  candidate_start date;
  candidate_end date;
  previous_end date;
  result nocendland.finance_period;
begin
  if current_user_id is null then
    raise exception 'authentication_required';
  end if;

  if target_date is null then
    raise exception 'target_date_required';
  end if;

  select * into result
  from nocendland.finance_period
  where id_user = current_user_id
    and target_date between starts_on and ends_on
  order by starts_on desc
  limit 1;

  if result.id is not null then
    return result;
  end if;

  insert into nocendland.finance_settings (id_user)
  values (current_user_id)
  on conflict (id_user) do nothing;

  insert into nocendland.finance_category (id_user, name, flow_type, sort_order)
  values
    (current_user_id, 'Nómina', 'income', 10),
    (current_user_id, 'Otros ingresos', 'income', 20),
    (current_user_id, 'Vivienda', 'expense', 30),
    (current_user_id, 'Alimentación', 'expense', 40),
    (current_user_id, 'Transporte', 'expense', 50),
    (current_user_id, 'Ocio', 'expense', 60),
    (current_user_id, 'Suscripciones', 'expense', 70),
    (current_user_id, 'Otros gastos', 'expense', 80),
    (current_user_id, 'Ahorro', 'saving', 90),
    (current_user_id, 'Inversión', 'saving', 100)
  on conflict do nothing;

  select period_start_day into configured_start_day
  from nocendland.finance_settings
  where id_user = current_user_id;

  target_month := date_trunc('month', target_date)::date;
  candidate_start := target_month + (
    least(
      configured_start_day::integer,
      extract(day from (target_month + interval '1 month - 1 day'))::integer
    ) - 1
  );

  if target_date < candidate_start then
    previous_month := (target_month - interval '1 month')::date;
    candidate_start := previous_month + (
      least(
        configured_start_day::integer,
        extract(day from (previous_month + interval '1 month - 1 day'))::integer
      ) - 1
    );
  end if;

  next_month := (date_trunc('month', candidate_start) + interval '1 month')::date;
  candidate_end := next_month + (
    least(
      configured_start_day::integer,
      extract(day from (next_month + interval '1 month - 1 day'))::integer
    ) - 1
  ) - 1;

  select max(ends_on) into previous_end
  from nocendland.finance_period
  where id_user = current_user_id
    and ends_on < target_date;

  if previous_end is not null and candidate_start <= previous_end then
    candidate_start := previous_end + 1;
  end if;

  insert into nocendland.finance_period (id_user, starts_on, ends_on)
  values (current_user_id, candidate_start, candidate_end)
  on conflict (id_user, starts_on) do nothing;

  select * into result
  from nocendland.finance_period
  where id_user = current_user_id
    and starts_on = candidate_start;

  with recurring_candidates as (
    select
      recurring.id,
      recurring.category_id,
      recurring.goal_id,
      recurring.name,
      recurring.amount,
      recurring.starts_on as recurring_starts_on,
      recurring.ends_on as recurring_ends_on,
      recurring.interval_months,
      generated_month.month_start::date as month_start,
      generated_month.month_start::date + (
        least(
          recurring.due_day::integer,
          extract(day from (generated_month.month_start + interval '1 month - 1 day'))::integer
        ) - 1
      ) as due_on,
      (
        extract(year from generated_month.month_start)::integer * 12
        + extract(month from generated_month.month_start)::integer
        - extract(year from date_trunc('month', recurring.starts_on))::integer * 12
        - extract(month from date_trunc('month', recurring.starts_on))::integer
      ) as month_distance
    from nocendland.finance_recurring_item recurring
    cross join lateral generate_series(
      date_trunc('month', result.starts_on)::date,
      date_trunc('month', result.ends_on)::date,
      interval '1 month'
    ) as generated_month(month_start)
    where recurring.id_user = current_user_id
      and recurring.archived_at is null
      and recurring.starts_on <= result.ends_on
      and (recurring.ends_on is null or recurring.ends_on >= result.starts_on)
  )
  insert into nocendland.finance_movement (
    id_user,
    period_id,
    category_id,
    recurring_item_id,
    goal_id,
    name,
    amount,
    status,
    scheduled_on,
    recurrence_due_on
  )
  select
    current_user_id,
    result.id,
    candidate.category_id,
    candidate.id,
    candidate.goal_id,
    candidate.name,
    candidate.amount,
    'pending',
    candidate.due_on,
    candidate.due_on
  from recurring_candidates candidate
  where candidate.month_distance >= 0
    and mod(candidate.month_distance, candidate.interval_months) = 0
    and candidate.due_on between result.starts_on and result.ends_on
    and candidate.due_on >= candidate.recurring_starts_on
    and (
      candidate.recurring_ends_on is null
      or candidate.due_on <= candidate.recurring_ends_on
    )
  on conflict do nothing;

  return result;
end;
$$;

revoke execute on function nocendland.ensure_finance_period(date) from public, anon;
grant execute on function nocendland.ensure_finance_period(date) to authenticated, service_role;
