create table nocendland.finance_settings (
  id_user uuid primary key
    references nocendland."user"(id) on update cascade on delete cascade,
  currency_code text not null default 'EUR',
  period_start_day smallint not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint finance_settings_currency_code_check
    check (currency_code ~ '^[A-Z]{3}$'),
  constraint finance_settings_period_start_day_check
    check (period_start_day between 1 and 31)
);

create table nocendland.finance_category (
  id bigint generated by default as identity primary key,
  id_user uuid not null
    references nocendland."user"(id) on update cascade on delete cascade,
  name text not null,
  flow_type text not null,
  sort_order integer not null default 0,
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint finance_category_id_owner_key unique (id, id_user),
  constraint finance_category_name_check check (btrim(name) <> ''),
  constraint finance_category_flow_type_check
    check (flow_type in ('income', 'expense', 'saving')),
  constraint finance_category_sort_order_check check (sort_order >= 0)
);

create unique index finance_category_owner_flow_name_key
  on nocendland.finance_category (id_user, flow_type, lower(btrim(name)));

create table nocendland.finance_period (
  id bigint generated by default as identity primary key,
  id_user uuid not null
    references nocendland."user"(id) on update cascade on delete cascade,
  starts_on date not null,
  ends_on date not null,
  opening_balance numeric(14, 2) not null default 0,
  status text not null default 'open',
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint finance_period_id_owner_key unique (id, id_user),
  constraint finance_period_owner_start_key unique (id_user, starts_on),
  constraint finance_period_dates_check check (ends_on >= starts_on),
  constraint finance_period_status_check check (status in ('open', 'closed')),
  constraint finance_period_closed_at_check check (
    (status = 'open' and closed_at is null)
    or (status = 'closed' and closed_at is not null)
  )
);

create table nocendland.finance_goal (
